--
--  السبب: الموقع يعرض حالياً 15 هدفاً تحت عنوان «أهداف الجودة المعتمدة»،
--  وهي غير موجودة في وثيقة الأهداف. هذا الملف يستبدلها بالأهداف الأحد عشر
--  للعام 2026/2027 كما وردت في ISO-GEN-OB-01 (التعديل 1) بصياغة مختصرة.
