begin;

create table if not exists public.site_settings_bk_20261009 as table public.site_settings;
alter table public.site_settings_bk_20261009 enable row level security;
revoke all on public.site_settings_bk_20261009 from anon, authenticated;

update public.site_settings
   set value = $q$[
  "إغلاق حالات عدم المطابقة الاثنتي عشرة الصادرة عن الجهة المانحة DNV والحصول على شهادة المطابقة للمواصفة ISO 21001:2018 — 12 من 12 بحلول 31/12/2026",
  "تطبيق المراجعة المزدوجة للتصحيح والرصد على جميع امتحانات نهاية الترم، دون أي تعديل على النتائج بعد اعتمادها إلا بتظلم مقبول — 100 %",
  "إنذار كل متعلم يتجاوز حد الغياب وإخطار ولي أمره خلال ثلاثة أيام عمل من تاريخ التجاوز — 100 %",
  "رضا المتعلمين وأولياء الأمور والعاملين بنسبة 90 % فأكثر، والرد على 95 % على الأقل من الشكاوى خلال خمسة أيام عمل",
  "استيفاء ملف كل تخصص من التخصصات السبعة بمكوناته العشرة، ومراجعة المقررات التخصصية بمدخلات من ورش الشركة — 7 من 7",
  "صفر إصابة للمتعلمين أثناء التدريب، بتوعية 100 % من المتعلمين قبل كل فترة تدريب وتنفيذ تجربتَي إخلاء في العام",
  "تنفيذ 90 % على الأقل من خطة تدريب العاملين، وزيارة صفية وتقييم لكل مدرس ومدرب في كل ترم",
  "تطوير البنية التكنولوجية للإدارات: خمسة أجهزة حاسب وطابعة ألوان وطابعة شهادات، وتشغيل الإدارات الخمس على السيستم بحساب مستقل لكل مستخدم، وتشغيل المكتبة الرقمية",
  "عقد اجتماعين لمجلس أولياء الأمور في كل ترم، وتفعيل بوابة ولي الأمر لـ 70 % فأكثر من أولياء الأمور",
  "إصدار 95 % على الأقل من شهادات الخريجين خلال سبعة أيام عمل من تاريخ الطلب",
  "تحويل الفصول الدراسية إلى فصول تفاعلية بتركيب 12 شاشة تفاعلية مقاس 75 بوصة، وتدريب جميع المدرسين على استخدامها"
]$q$::jsonb
 where key = 'about.objectives';

do $$
begin
  if (select jsonb_array_length(value) from public.site_settings where key = 'about.objectives') <> 11 then
    raise exception 'لم يتم تحديث الأهداف';
  end if;
end $$;

commit;
